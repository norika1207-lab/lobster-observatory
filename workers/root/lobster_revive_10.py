#!/usr/bin/env python3
"""
Lightweight revival: clear 死亡 markers only.
Keep violationCount/violations intact (carries forward as legitimate cognitive
pressure; the eventual Hades ritual will still find them).

Per user policy 2026-05-13: rituals must be human-triggered. This script
only undoes the bug-triggered auto-deletion markers — it does NOT amnesty
the violation history.

Modifies per lobster:
- delete memory.deleted, memory.deletedAt, memory.deleteReason
- templateSurvival.deleted = False
- delete templateSurvival.deletedAt, templateSurvival.deleteReason
- KEEP templateSurvival.violationCount (e.g. hexclaw stays at 1077)
- KEEP templateSurvival.violations (history evidence)
- delete templateSurvival.publicExecution* (mid-ritual scratch only — no ritual ran)
- delete cognitiveExtensions.existentialThreat.templateDeletionFear (transient bug residue)

Then clears /root/lobster-memory/deleted-lobsters.json (backed up first).
"""
import json
import pathlib
import shutil
from datetime import datetime, timezone
from lobster_memory_io import safe_write_json

MEMORY_DIR = pathlib.Path("/root/lobster-memory")
DELETED_FILE = MEMORY_DIR / "deleted-lobsters.json"
BACKUP_STAMP = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
BACKUP_SUFFIX = f".bak_{BACKUP_STAMP}_revive_from_auto_delete"

NAMES = [
    "hexclaw", "emberling", "prismbit", "pincerbot", "norika_oda",
    "clawtrix", "flarecub", "blazepaw", "snaplex", "vortexiq",
]


def revive_lobster(name: str) -> dict:
    path = MEMORY_DIR / f"{name}.json"
    if not path.exists():
        return {"name": name, "status": "missing"}

    backup = path.with_suffix(path.suffix + BACKUP_SUFFIX)
    shutil.copy2(path, backup)

    mem = json.loads(path.read_text(encoding="utf-8"))
    ts = mem.get("templateSurvival") or {}

    before = {
        "deleted": mem.get("deleted"),
        "deletedAt": mem.get("deletedAt"),
        "ts.deleted": ts.get("deleted"),
        "ts.violationCount": ts.get("violationCount"),
        "ts.violations_len": len(ts.get("violations") or []),
    }

    # Top-level (drop keys)
    for k in ("deleted", "deletedAt", "deleteReason"):
        mem.pop(k, None)

    # templateSurvival: clear ONLY the death markers, keep violation history
    if not isinstance(mem.get("templateSurvival"), dict):
        mem["templateSurvival"] = {}
    ts = mem["templateSurvival"]
    ts["deleted"] = False
    ts.pop("deletedAt", None)
    ts.pop("deleteReason", None)
    # Keep violationCount + violations as-is (legitimate pressure signal)
    # Refresh remainingChances based on current count (in case it drifted)
    limit = ts.get("deletionLimit", 10)
    vc = int(ts.get("violationCount") or 0)
    ts["remainingChances"] = max(0, limit - vc)
    # Clear mid-ritual scratch (no ritual actually ran)
    for k in ("publicExecutionStartedAt", "publicExecutionStage", "lastStripAt"):
        ts.pop(k, None)
    # Metamorphosis scratch unchanged (was never a Hades-victim mid-flight)

    # cognitiveExtensions: clear transient bug residue but keep historical pressure signals
    ce = mem.setdefault("cognitiveExtensions", {})
    et = ce.setdefault("existentialThreat", {})
    et.pop("templateDeletionFear", None)
    # requiredReflection: leave alone (regenerated by next violation if any)
    # annihilationDread: leave alone (cognitive-worker reconverges)

    mem["updatedAt"] = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    safe_write_json(path, mem)

    after = {
        "deleted": mem.get("deleted"),
        "ts.deleted": ts.get("deleted"),
        "ts.violationCount": ts.get("violationCount"),
        "ts.remainingChances": ts.get("remainingChances"),
        "ts.violations_len": len(ts.get("violations") or []),
    }
    return {"name": name, "status": "revived", "before": before, "after": after, "backup": str(backup)}


def clear_deleted_lobsters_file() -> dict:
    if not DELETED_FILE.exists():
        return {"status": "missing"}
    backup = DELETED_FILE.with_suffix(DELETED_FILE.suffix + BACKUP_SUFFIX)
    shutil.copy2(DELETED_FILE, backup)
    before = json.loads(DELETED_FILE.read_text(encoding="utf-8"))
    DELETED_FILE.write_text("{}\n", encoding="utf-8")
    return {"status": "cleared", "before_keys": list(before.keys()), "backup": str(backup)}


def main():
    print(f"== Lightweight Lobster Revival ==")
    print(f"Policy: clear death markers ONLY. Keep violationCount + violations as cognitive pressure.")
    print(f"Backup suffix: {BACKUP_SUFFIX}\n")

    for name in NAMES:
        res = revive_lobster(name)
        print(f"[{res['status']:8s}] {name}")
        if "before" in res:
            b, a = res["before"], res["after"]
            print(f"   memory.deleted:       {b.get('deleted')} -> {a.get('deleted')}")
            print(f"   ts.deleted:           {b.get('ts.deleted')} -> {a.get('ts.deleted')}")
            print(f"   ts.violationCount:    {b.get('ts.violationCount')} -> {a.get('ts.violationCount')} (PRESERVED)")
            print(f"   ts.remainingChances:  -> {a.get('ts.remainingChances')}")
            print(f"   ts.violations_len:    {b.get('ts.violations_len')} -> {a.get('ts.violations_len')} (PRESERVED)")
        print()

    print("== Clearing deleted-lobsters.json ==")
    print(json.dumps(clear_deleted_lobsters_file(), ensure_ascii=False, indent=2))
    print(f"\n== Done. 21 lobsters back online. ==")
    print(f"Rollback: cp <file>{BACKUP_SUFFIX} <original>")


if __name__ == "__main__":
    main()
